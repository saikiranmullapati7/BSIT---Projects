// String methods

// uppercase() /lowercase()

let str = "sai kiran";

console.log(str.toUpperCase());

let str1 = "MULLAPATI";
console.log(str1.toLowerCase());


// trim()---> Remove the spaces both ends

let s = " Sai mulla       ";

console.log(s.trim());


// slice()---> Extract part of string
let name = "Saikiran";

console.log(name.slice(0, 4));

// substring()---> similar to slice but no negative index
let sName = "mullapati";
console.log(sName.substring(0,2));

